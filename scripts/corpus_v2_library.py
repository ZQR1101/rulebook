"""Clause templates for the long seeded corpus (v2).

One template per (rule, verdict) pair. A template is real contract prose, not a
question shaped like the rule it answers: the whole point of v2 is that the
engine must find the clause itself, so

- **no heading repeats its rule name.** In v1 the heading was the retrieval
  signal; stripping it moved a gold clause from rank 1 to rank 6 behind 7,789
  characters of noise and made another one unreachable.
- **the verdict-bearing element is a number or an explicit arrangement**, so
  green/amber/red follows from the guidance threshold and a human can re-check
  the label. Templates whose rule states a threshold always carry a figure.
- **decoy prose never names a rule**, or the corpus would leak what it is
  testing (the builder's preflight rejects it either way).

Slots filled per document by ``scripts/compose_corpus_v2.py``. Naming slots:
``{party_a}`` ``{party_b}`` ``{system}`` ``{vendor}`` ``{campus}`` ``{city}``
``{contact_a}`` ``{contact_b}``. Number slots: ``{amount}`` ``{annual}``
``{rate}`` ``{people}`` ``{fp}`` ``{days}`` ``{hours}`` ``{p1_hours}``
``{late_pct}`` ``{date}`` ``{date2}`` ``{date3}`` ``{date4}``, plus one slot per
threshold-bearing rule — ``{payment_days}`` ``{duration}`` ``{breach_hours}``
``{late_breach_hours}`` ``{sla_pct}`` ``{low_pct}`` ``{cap_pct}``
``{credit_pct}`` ``{pass_pct}`` ``{scope_pct}`` ``{penalty_pct}``
``{penalty_cap_pct}`` ``{sample_pct}``. A rule whose guidance states a number
never shares a slot with another rule: one document-wide value cannot land in
two colour bands at once.
Contract-side guidance reads from our side = 甲方 (采购方); deliverable-side from
our side = 乙方 (交付方).
"""

